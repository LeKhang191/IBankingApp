# Internal helper for the three double-click launchers in the repository root.
# Windows PowerShell 5.1 compatible. No Python, Node, npm or pytest required on host.
[CmdletBinding()]
param([ValidateSet('app','automation','e2e')][string]$Mode)
$ErrorActionPreference = 'Stop'
$root = [System.IO.Path]::GetFullPath((Join-Path $PSScriptRoot '..'))
Set-Location $root

function Step([string]$message) { Write-Host "`n[IBANKING] $message" -ForegroundColor Cyan }
function Fail([string]$message) { throw $message }
function Invoke-DockerChecked([string[]]$Arguments) {
    & docker @Arguments
    if ($LASTEXITCODE -ne 0) { Fail "Docker failed (exit $LASTEXITCODE): docker $($Arguments -join ' ')" }
}
function RandomHex([int]$byteCount) {
    $buf = New-Object byte[] $byteCount
    $rng = [System.Security.Cryptography.RandomNumberGenerator]::Create()
    try { $rng.GetBytes($buf) } finally { $rng.Dispose() }
    return ([BitConverter]::ToString($buf)).Replace('-', '').ToLowerInvariant()
}
function Test-DockerEngine {
    # Native stderr can otherwise become a terminating error in Windows PowerShell.
    $prior = $ErrorActionPreference
    $ErrorActionPreference = 'Continue'
    try {
        & docker info --format '{{.ServerVersion}}' 2>$null | Out-Null
        return ($LASTEXITCODE -eq 0)
    } finally { $ErrorActionPreference = $prior }
}
function Ensure-Docker {
    Step 'Checking Docker and Docker Compose...'
    if (-not (Get-Command docker -ErrorAction SilentlyContinue)) {
        Fail 'Docker CLI was not found. Install Docker Desktop for Windows, enable WSL2/Linux containers and rerun.'
    }
    & docker compose version
    if ($LASTEXITCODE -ne 0) { Fail 'Docker Compose V2 is missing. Update Docker Desktop.' }
    $available = Test-DockerEngine
    if ($available) { return }
    $locations = @(
        (Join-Path $env:ProgramFiles 'Docker\Docker\Docker Desktop.exe'),
        (Join-Path $env:LOCALAPPDATA 'Programs\DockerDesktop\Docker Desktop.exe')
    )
    $desktop = $locations | Where-Object { Test-Path $_ } | Select-Object -First 1
    if ($desktop) {
        Step 'Starting Docker Desktop...'
        Start-Process -FilePath $desktop | Out-Null
        $ready = $false
        for ($i=0; $i -lt 60; $i++) {
            Start-Sleep -Seconds 3
            if (Test-DockerEngine) { $ready = $true; break }
        }
        if ($ready) { return }
    }
    Fail 'Docker Engine is not ready. Open Docker Desktop, wait for Engine Running, then rerun.'
}
function Ensure-Env {
    if (Test-Path (Join-Path $root '.env')) {
        Step 'Using existing .env (never overwriting credentials or databases).'
        return
    }
    Step 'No .env found: generating application configuration with random secrets...'
    $values = [ordered]@{
        'POSTGRES_HOST'='postgres'; 'POSTGRES_PORT'='5432'; 'POSTGRES_USER'='postgres'
        'POSTGRES_PASSWORD'=(RandomHex 24); 'POSTGRES_DB'='ibanking'
        'AUTH_DB_NAME'='auth_db'; 'AUTH_DB_USER'='auth_user'; 'AUTH_DB_PASSWORD'=(RandomHex 24)
        'TUITION_DB_NAME'='tuition_db'; 'TUITION_DB_USER'='tuition_user'; 'TUITION_DB_PASSWORD'=(RandomHex 24)
        'PAYMENT_DB_NAME'='payment_db'; 'PAYMENT_DB_USER'='payment_user'; 'PAYMENT_DB_PASSWORD'=(RandomHex 24)
        'SEED_DEMO_DATA'='true'; 'JWT_SECRET_KEY'=(RandomHex 32); 'JWT_ALGORITHM'='HS256'
        'JWT_EXPIRE_MINUTES'='60'; 'INTERNAL_SERVICE_TOKEN'=(RandomHex 32); 'OTP_PEPPER'=(RandomHex 32)
        'OTP_LENGTH'='6'; 'OTP_EXPIRE_MINUTES'='5'; 'OTP_MAX_ATTEMPTS'='5'
        'OTP_MAX_RESENDS'='3'; 'OTP_RESEND_COOLDOWN_SECONDS'='30'
        'CORS_ALLOW_ORIGINS'='http://localhost:5173'
        'VITE_API_URL'='http://localhost:8080'; 'VITE_TUITION_API_URL'='http://localhost:8080'
        'VITE_PAYMENT_API_URL'='http://localhost:8080'
        'SMTP_HOST'='smtp.gmail.com'; 'SMTP_PORT'='587'; 'SMTP_USER'=''; 'SMTP_PASSWORD'=''
        'EMAIL_FROM'=''
        'SAGA_LEASE_SECONDS'='90'; 'SAGA_RETRY_SECONDS'='10'
        'OUTBOX_POLL_SECONDS'='3'; 'OUTBOX_LEASE_SECONDS'='60'; 'LOG_LEVEL'='INFO'
    }
    $lines = @('# Generated by one-click launcher. Keep this file private; do not commit to Git.')
    foreach ($key in $values.Keys) { $lines += "${key}=$($values[$key])" }
    [System.IO.File]::WriteAllLines((Join-Path $root '.env'), [string[]]$lines, (New-Object System.Text.UTF8Encoding($false)))
    Write-Host 'Local .env created. Database credentials and service secrets were randomly generated.' -ForegroundColor Green
}
# Gmail settings are user-supplied; never generate or log Gmail credentials.
# Existing .env is preserved unless the Gmail fields are empty/placeholder/demo.
function Ensure-GmailSmtp {
    $envPath = Join-Path $root '.env'
    $lines = New-Object 'System.Collections.Generic.List[string]'
    foreach ($line in [System.IO.File]::ReadAllLines($envPath)) { [void]$lines.Add($line) }
    $settings = @{}
    foreach ($line in $lines) {
        if ($line -match '^\s*([A-Za-z_][A-Za-z0-9_]*)\s*=\s*(.*)$') {
            $settings[$matches[1]] = $matches[2].Trim().Trim('"', "'")
        }
    }
    $email = [string]$settings['SMTP_USER']
    $password = [string]$settings['SMTP_PASSWORD']
    $hostName = [string]$settings['SMTP_HOST']
    $needsSetup = [string]::IsNullOrWhiteSpace($email) -or
        [string]::IsNullOrWhiteSpace($password) -or
        $email -match '^(your_|replace_|example)' -or
        $password -match '^(your_|replace_|example)' -or
        $hostName -ne 'smtp.gmail.com'
    if (-not $needsSetup) {
        Step 'Existing Gmail SMTP credentials found in .env; preserving them.'
        return
    }
    Step 'Gmail configuration required for real OTP and receipt emails.'
    Write-Host 'Use a Google App Password (NOT the normal Gmail sign-in password).'
    Write-Host 'App Password requires Google 2-Step Verification on eligible accounts.'
    do {
        $email = (Read-Host 'Gmail address (leave empty to cancel)').Trim()
        if (-not $email) { Fail 'Gmail is required for the main application. Setup cancelled; .env retained.' }
        if ($email -notmatch '^[^\s@]+@[^\s@]+\.[^\s@]+$') {
            Write-Host 'Invalid email address. Please try again.' -ForegroundColor Yellow
        }
    } until ($email -match '^[^\s@]+@[^\s@]+\.[^\s@]+$')
    $secure = Read-Host 'Google App Password (input hidden)' -AsSecureString
    $ptr = [Runtime.InteropServices.Marshal]::SecureStringToBSTR($secure)
    try {
        $password = [Runtime.InteropServices.Marshal]::PtrToStringBSTR($ptr)
    } finally {
        [Runtime.InteropServices.Marshal]::ZeroFreeBSTR($ptr)
    }
    # Google shows App Passwords in four groups; remove pasted spaces.
    $password = $password -replace '\s', ''
    if ($password -notmatch '^[A-Za-z0-9]{16}$') {
        Fail 'Expected a 16-character Google App Password. Setup cancelled; .env retained.'
    }
    $updates = [ordered]@{
        SMTP_HOST = 'smtp.gmail.com'
        SMTP_PORT = '587'
        SMTP_USER = $email
        SMTP_PASSWORD = $password
        EMAIL_FROM = "iBanking <$email>"
    }
    foreach ($key in $updates.Keys) {
        $found = $false
        for ($i = 0; $i -lt $lines.Count; $i++) {
            if ($lines[$i] -match ('^\s*' + [regex]::Escape($key) + '\s*=')) {
                $lines[$i] = "${key}=$($updates[$key])"
                $found = $true
                break
            }
        }
        if (-not $found) { [void]$lines.Add("${key}=$($updates[$key])") }
    }
    [System.IO.File]::WriteAllLines($envPath, [string[]]$lines.ToArray(), (New-Object System.Text.UTF8Encoding($false)))
    Write-Host 'Gmail SMTP saved to .env. Keep this file private.' -ForegroundColor Green
    $password = $null
}

# Read a short, local-only diagnostic without printing or changing credentials.
function Get-MainBootstrapLogs {
    $prior = $ErrorActionPreference
    $ErrorActionPreference = 'Continue'
    try {
        $lines = & docker compose -f docker-compose.yml logs --no-color --tail=100 db-bootstrap 2>&1
        return ($lines | Out-String)
    } finally {
        $ErrorActionPreference = $prior
    }
}
function Start-MainStack {
    $compose = @('compose','-f','docker-compose.yml')
    Invoke-DockerChecked -Arguments ($compose + @('config','--quiet'))
    try {
        Invoke-DockerChecked -Arguments ($compose + @('up','-d','--build'))
    } catch {
        $originalError = $_
        $bootstrapLogs = Get-MainBootstrapLogs
        # A database initialized using an older .env retains the old password in pgdata.
        # Recover only this positively identified problem, and only for the demo app stack.
        if ($bootstrapLogs -notmatch 'password authentication failed for user ["'']postgres["'']') {
            throw $originalError
        }
        Step 'Detected stale PostgreSQL password in the MAIN demo database volume.'
        Write-Host '[DEMO RESET] Removing main app Compose volumes to regenerate demo databases.' -ForegroundColor Yellow
        Write-Host 'Only do this with disposable demo data; all main app Compose volumes will be deleted.' -ForegroundColor Yellow
        Write-Host 'The .env file and the isolated E2E Compose project are not changed.' -ForegroundColor Yellow
        Invoke-DockerChecked -Arguments ($compose + @('down','-v','--remove-orphans'))
        Step 'Rebuilding demo database from the existing, unchanged .env...'
        Invoke-DockerChecked -Arguments ($compose + @('up','-d','--build'))
    }
}

function Wait-Http([string]$url, [int]$attempts=40) {
    for ($i=0; $i -lt $attempts; $i++) {
        try {
            $response = Invoke-WebRequest -Uri $url -UseBasicParsing -TimeoutSec 4
            if ($response.StatusCode -ge 200 -and $response.StatusCode -lt 400) { return }
        } catch { }
        Start-Sleep -Seconds 3
    }
    Fail "Timed out waiting for $url. Check: docker compose ps; docker compose logs --tail=80"
}
function Setup-TestStack {
    Step 'Building and starting the ISOLATED E2E stack (separate PostgreSQL volume)...'
    Invoke-DockerChecked -Arguments @('compose','-f','docker-compose.e2e.yml','config','--quiet')
    Invoke-DockerChecked -Arguments @('compose','-f','docker-compose.e2e.yml','up','-d','--build')
    Wait-Http 'http://localhost:18080/health' 50
}

try {
    Ensure-Docker
    Ensure-Env
    if ($Mode -eq 'app') {
        Step 'Building images and starting all application services...'
        # Main application uses real Gmail SMTP from .env (no Mailpit demo override).
        Ensure-GmailSmtp
        # Force browser API URLs for this process; do not overwrite .env.
        $env:VITE_API_URL='http://localhost:8080'
        $env:VITE_TUITION_API_URL='http://localhost:8080'
        $env:VITE_PAYMENT_API_URL='http://localhost:8080'
        $env:CORS_ALLOW_ORIGINS='http://localhost:5173'
        Start-MainStack
        Step 'Checking API Gateway and frontend...'
        Wait-Http 'http://localhost:8080/health' 50
        Wait-Http 'http://localhost:5173' 50
        Write-Host 'Application: http://localhost:5173' -ForegroundColor Green
        Write-Host 'OTP and receipts are sent through the Gmail SMTP account in .env.' -ForegroundColor Green
        Start-Process 'http://localhost:5173/dang-nhap'
    }
    elseif ($Mode -eq 'automation') {
        Setup-TestStack
        Step 'AUTOMATION 1/2: Saga + Outbox workflow smoke test...'
        Invoke-DockerChecked -Arguments @('compose','-f','docker-compose.e2e.yml','exec','-T','payment-service','python','-m','app.tests.phase3_saga_smoke')
        Step 'AUTOMATION 2/2: concurrent debit + tuition settlement on disposable PostgreSQL...'
        # e2e-tests container already includes Python. Install test requirements inside it.
        # DSN is supplied inside the container, never configured on the host.
        $command = 'pip install --disable-pip-version-check -q -r /tests/e2e/requirements.txt && TEST_DATABASE_URL="$E2E_PAYMENT_DSN" python -m pytest -v -p no:cacheprovider /tests/automation/test_postgres_concurrency.py'
        Invoke-DockerChecked -Arguments @('compose','-f','docker-compose.e2e.yml','run','--rm','e2e-tests','sh','-c',$command)
        Write-Host "`n[PASS] All automation tests passed." -ForegroundColor Green
    }
    elseif ($Mode -eq 'e2e') {
        Setup-TestStack
        Step 'Running real HTTP E2E: login, OTP, payment, Saga, concurrency, receipt...'
        Invoke-DockerChecked -Arguments @('compose','-f','docker-compose.e2e.yml','run','--rm','e2e-tests')
        Write-Host "`n[PASS] All E2E tests passed." -ForegroundColor Green
        Write-Host 'Mailpit inbox: http://localhost:18025'
    }
    exit 0
} catch {
    Write-Host "`n[FAILED] $($_.Exception.Message)" -ForegroundColor Red
    Write-Host 'Check the message above and run: docker compose -f docker-compose.yml logs --tail=100 db-bootstrap postgres' -ForegroundColor Yellow
    exit 1
}
